export function translator(lang) {
  const dict = lang === "en" ? en : ja;
  return (key, vars) => {
    let s = dict[key] ?? ja[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}
